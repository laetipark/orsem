const nullableNumber = z
  .string()
  .refine((value) => value.trim() !== '' && Number.isFinite(Number(value)))
  .nullable();
export const marketStatusSchema = z.enum([
  'AVAILABLE',
  'STALE',
  'NOT_CONFIGURED',
  'WAITING',
  'UNAVAILABLE',
  'EMBEDDED',
]);
export const marketQuoteSchema = marketInstrumentSchema.extend({
  status: marketStatusSchema,
  value: nullableNumber,
  change: nullableNumber,
  changePercent: nullableNumber,
  changeUnit: z.enum(['percent', 'bp']),
  changeLabel: z.string(),
  valueDate: z.string().nullable(),
  providerAt: z.string().datetime().nullable(),
  observedAt: z.string().datetime().nullable(),
  referenceValue: nullableNumber,
  referenceDate: z.string().nullable(),
  convertedValue: nullableNumber,
  conversionRate: nullableNumber,
  conversionAt: z.string().datetime().nullable(),
  message: z.string().nullable(),
});
export type MarketQuote = z.infer<typeof marketQuoteSchema>;
export const marketHistoryRangeSchema = z.enum(['1m', '3m', '1y']);
export type MarketHistoryRange = z.infer<typeof marketHistoryRangeSchema>;
export const marketHistorySchema = z.object({
  asOf: z.string().datetime(),
  instrument: marketInstrumentSchema,
  range: marketHistoryRangeSchema,
  points: z.array(z.object({ date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/), value: z.string() })),
  historyKind: marketInstrumentSchema.shape.historyKind,
  status: marketStatusSchema,
  message: z.string().nullable(),
  sourceUrl: z.string().url(),
});
export type MarketHistory = z.infer<typeof marketHistorySchema>;
export const marketOverviewSchema = z.object({
  asOf: z.string().datetime(),
  items: z.array(marketQuoteSchema),
  histories: z.record(z.string(), marketHistorySchema).optional(),
});
export type MarketOverview = z.infer<typeof marketOverviewSchema>;
