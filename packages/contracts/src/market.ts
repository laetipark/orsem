import { z } from 'zod';
import { RightsMode } from './enums';

export const marketInstrumentSchema = z.object({
  id: z.string().min(1).max(32),
  name: z.string(),
  region: z.enum(['kr', 'us', 'global']),
  category: z.enum(['INDEX', 'FX', 'BOND', 'METAL', 'ENERGY', 'CRYPTO']),
  currency: z.enum(['KRW', 'USD']).nullable(),
  unit: z.string(),
  provider: z.enum(['TOSS', 'BITHUMB', 'TREASURY', 'GOLD_API', 'EIA', 'TRADINGVIEW', 'FRED']),
  symbol: z.string(),
  sourceUrl: z.string().url(),
  attribution: z.string(),
  rightsMode: z.enum(RightsMode),
  displayKind: z.enum(['NATIVE', 'WIDGET']),
  widgetSymbol: z.string().nullable(),
  historyKind: z.enum(['close', 'daily_average', 'yield', 'observed']),
  description: z.string(),
});
export type MarketInstrument = z.infer<typeof marketInstrumentSchema>;

